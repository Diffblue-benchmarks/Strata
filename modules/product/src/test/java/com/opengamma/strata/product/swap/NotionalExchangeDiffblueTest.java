  @Test
  @DisplayName("Test meta()")
  @Tag("ContributionFromDiffblue")
  @ManagedByDiffblue
  @MethodsUnderTest({"Meta NotionalExchange.meta()"})
  void testMeta() {
    // Arrange and Act
    Meta actualMetaResult = NotionalExchange.meta();

    // Assert
    MetaProperty<Payment> paymentResult = actualMetaResult.payment();
    assertTrue(paymentResult instanceof DirectMetaProperty);
    assertEquals("payment", paymentResult.name());
    assertEquals(PropertyStyle.IMMUTABLE, paymentResult.style());
    assertTrue(actualMetaResult.isBuildable());
    Class<Payment> expectedPropertyTypeResult = Payment.class;
    assertEquals(expectedPropertyTypeResult, paymentResult.propertyType());
    Class<NotionalExchange> expectedDeclaringTypeResult = NotionalExchange.class;
    assertEquals(expectedDeclaringTypeResult, paymentResult.declaringType());
    assertSame(Meta.INSTANCE, paymentResult.metaBean());
  }

